pub fn fill_missing_guide(tool: &mut Tool) {
    if !tool.scenarios.is_empty() && !tool.usage_steps.is_empty() && !tool.key_tips.is_empty() {
        return;
    }
    if let Some(g) = lookup_builtin_guide(&tool.id) {
        if tool.scenarios.is_empty() {
            tool.scenarios = g.scenarios.iter().map(|s| (*s).to_string()).collect();
        }
        if tool.usage_steps.is_empty() {
            tool.usage_steps = g.usage_steps.iter().map(|s| (*s).to_string()).collect();
        }
        if tool.key_tips.is_empty() {
            tool.key_tips = g.key_tips.iter().map(|s| (*s).to_string()).collect();
        }
    } else {
        let (sc, us, kt) = fallback_guide(&tool.category_id, &tool.kind);
        if tool.scenarios.is_empty() {
            tool.scenarios = sc;
        }
        if tool.usage_steps.is_empty() {
            tool.usage_steps = us;
        }
        if tool.key_tips.is_empty() {
            tool.key_tips = kt;
        }
    }
}
